// Builds src/ui/illustration-index.ts from public/illustrations/generated/manifest.json,
// adding each asset's intrinsic size (read from the PNG header) so <Illustration>
// can set width/height and never shift the layout.
//   node scripts/gen-illustration-index.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const dir = path.join(root, "public/illustrations/generated")
const manifest = JSON.parse(fs.readFileSync(path.join(dir, "manifest.json"), "utf8"))

const out = {}
for (const a of manifest.assets) {
  const png = fs.readFileSync(path.join(root, "public", a.files.png))
  const w = png.readUInt32BE(16)
  const h = png.readUInt32BE(20)
  out[a.name] = { w, h, c: a.category, alt: a.purpose, svg: !!a.files.svg }
}

const body =
  "// Generated by scripts/gen-illustration-index.mjs from the manifest. Do not edit.\n" +
  "export type IllustrationMeta = { w: number; h: number; c: string; alt: string; svg: boolean }\n" +
  `export const ILLUSTRATIONS = ${JSON.stringify(out, null, 1)} as const satisfies Record<string, IllustrationMeta>\n` +
  "export type IllustrationName = keyof typeof ILLUSTRATIONS\n"
fs.writeFileSync(path.join(root, "src/ui/illustration-index.ts"), body)
console.log(`${Object.keys(out).length} assets`)
